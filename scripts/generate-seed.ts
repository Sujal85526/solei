/**
 * Generates supabase/seed.sql (local/demo data) from the launch content in
 * src/modules/content/seed.ts so the homepage fallback and the database never drift.
 *   pnpm db:seed:generate && pnpm db:reset
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  seedCategories,
  seedCosts,
  seedDestinations,
  seedInitialStock,
  seedPrices,
  seedSizes,
} from "../src/modules/content/seed";
import { DEV_OWNER_TOTP_SECRET, DEV_PASSWORD, DEV_USERS } from "./dev-users";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);

let sql = `-- GENERATED by scripts/generate-seed.ts — do not edit by hand.
-- Local / demo data: launch catalogue (8 destinations, 5 perfumes, 3 sprays) and opening stock.

insert into public.categories (slug, name, description, image_url, sort) values
${seedCategories.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(c.image)}, ${i})`).join(",\n")};

insert into public.destinations (slug, name, country, region, mood, story, postcard_image_url, hero_image_url, accent_colour, sort) values
${seedDestinations
  .map(
    (d, i) =>
      `  (${q(d.slug)}, ${q(d.name)}, ${q(d.country)}, ${q(d.region)}, ${q(d.mood)}, ${q(d.story)}, ${q(d.image)}, ${q(d.image)}, ${q(d.accent)}, ${i})`,
  )
  .join(",\n")};

`;

for (const [i, d] of seedDestinations.entries()) {
  const cat = d.category;
  const kind = cat === "perfume" ? "Perfume" : "All-over spray";
  const size = seedSizes[cat];
  const sku = `SOL-${cat === "perfume" ? "P" : "S"}-${d.slug.slice(0, 3).toUpperCase()}-${size}`;
  sql += `with p as (
  insert into public.products (category_id, destination_id, name, slug, description, featured, sort)
  select c.id, d.id, ${q(`${d.name} ${kind}`)}, ${q(`${d.slug}-${cat === "perfume" ? "perfume" : "all-over-spray"}`)}, ${q(d.story)}, true, ${i}
  from public.categories c, public.destinations d
  where c.slug = ${q(cat)} and d.slug = ${q(d.slug)}
  returning id
), img as (
  insert into public.product_images (product_id, url, alt, sort)
  select p.id, ${q(d.productImage)}, ${q(`Solei ${d.name} ${kind.toLowerCase()}`)}, 0 from p
  union all
  select p.id, ${q(d.image)}, ${q(`${d.name} — ${d.mood}`)}, 1 from p
), v as (
  insert into public.product_variants (product_id, label, size_ml, sku, price_fils, low_stock_threshold)
  select p.id, ${q(`${size} ml`)}, ${size}, ${q(sku)}, ${seedPrices[cat]}, 5 from p
  returning id
)
insert into public.variant_costs (variant_id, cost_fils) select v.id, ${seedCosts[cat]} from v;

`;
}

sql += `-- Opening stock in the main warehouse.
insert into public.stock_movements (variant_id, location_id, qty, type, reason)
select v.id, l.id, ${seedInitialStock}, 'receive', 'Opening stock (seed)'
from public.product_variants v
cross join public.stock_locations l
where l.is_default;
`;

/** `--catalog-only <file>`: catalogue + opening stock without dev logins (for hosted dev/staging DBs). */
const catalogOnlyIndex = process.argv.indexOf("--catalog-only");
if (catalogOnlyIndex > -1) {
  const out = process.argv[catalogOnlyIndex + 1] ?? "seed.catalog.sql";
  writeFileSync(out, sql);
  console.log(`wrote ${out} (catalog only)`);
  process.exit(0);
}

sql += `
-- LOCAL DEV staff accounts (password: ${DEV_PASSWORD}). See scripts/dev-users.ts.
`;
for (const u of DEV_USERS) {
  sql += `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change,
  email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)},
  extensions.crypt(${q(DEV_PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ full_name: u.name }))}, now(), now(), '', '', '', '');
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(u.id)}, ${q(u.id)}, ${q(JSON.stringify({ sub: u.id, email: u.email, email_verified: true }))}::jsonb, 'email', now(), now(), now());
insert into public.staff_profiles (user_id, full_name, email, role_id, position)
select ${q(u.id)}, ${q(u.name.replace(/ \(.*\)$/, ""))}, ${q(u.email)}, r.id, ${q(u.name.match(/\((.*)\)/)?.[1] ?? null)}
from public.roles r where r.key = ${q(u.role)};
`;
  if (u.totp) {
    sql += `insert into auth.mfa_factors (id, user_id, friendly_name, factor_type, status, created_at, updated_at, secret)
values (gen_random_uuid(), ${q(u.id)}, 'Dev authenticator', 'totp', 'verified', now(), now(), ${q(DEV_OWNER_TOTP_SECRET)});
`;
  }
}

writeFileSync(join(import.meta.dirname, "..", "supabase", "seed.sql"), sql);
console.log("wrote supabase/seed.sql");
